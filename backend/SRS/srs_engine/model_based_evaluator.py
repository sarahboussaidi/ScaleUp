def _value_counts(df, candidate_cols):
    if df is None or df.empty:
        return {}

    col = detect_column(df, candidate_cols)
    if not col:
        return {}

    return df[col].astype(str).value_counts().to_dict()


def _numeric_mean(df, candidate_cols):
    if df is None or df.empty:
        return None

    col = detect_column(df, candidate_cols)
    if not col:
        return None

    values = pd.to_numeric(df[col], errors="coerce").dropna()
    if values.empty:
        return None

    return round(float(values.mean()), 2)


def _safe_preview_rows(df, max_rows=8):
    if df is None or df.empty:
        return []

    preview = df.head(max_rows).copy()
    return preview.astype(str).to_dict(orient="records")


